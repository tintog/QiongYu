// Browser smoke test against the local application; no forecast fixtures are mocked.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const path = require('node:path')
async function main() {
  const browser = await chromium.launch({channel:'msedge', headless:true, args:['--enable-webgl','--ignore-gpu-blocklist']})
  const context = await browser.newContext({viewport:{width:1920,height:1080}})
  const base = process.env.SCREEN_URL || 'http://127.0.0.1:5175'
  const login = await context.request.post(base+'/api/auth/login',{data:{username:process.env.SCREEN_USER || 'admin',password:process.env.SCREEN_PASSWORD || 'Admin@2026',role:'admin'}})
  if (!login.ok()) throw new Error('Local test login failed: '+login.status())
  const page = await context.newPage(), errors=[]
  let imageryTiles=0,terrainTiles=0
  page.on('pageerror',e=>errors.push(e.message))
  page.on('response',r=>{if(r.status()>=400 && r.url().includes('/cesium/'))errors.push('Static asset '+r.status()+' '+r.url())})
  page.on('response',r=>{if(r.ok()&&r.url().includes('tiles.maps.eox.at'))imageryTiles++;if(r.ok()&&r.url().includes('ImageServer/tile/'))terrainTiles++})
  await page.goto(base)
  await page.getByRole('button',{name:'3D大屏',exact:true}).click()
  await page.waitForSelector('.screen-globe canvas',{timeout:90000})
  await page.waitForFunction(()=>!document.querySelector('.screen-loading'),{},{timeout:180000})
  console.log('INITIAL',await page.locator('.screen-alert').allTextContents())
  if(await page.locator('.screen-alert').count())throw new Error(await page.locator('.screen-alert').innerText())
  await page.waitForFunction(()=>!document.querySelector('.screen-risk')?.textContent.includes('待加载'),{},{timeout:120000})
  const s=page.locator('.weather-screen')
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.screen-note')).some(e=>e.textContent.includes('ArcGIS Terrain3D')),{},{timeout:45000})
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.screen-note')).some(e=>e.textContent.includes('Sentinel-2 2024')),{},{timeout:45000})
  await page.waitForFunction(()=>!document.querySelector('.screen-map-loading'),{},{timeout:90000})
  await page.screenshot({path:path.resolve('screen3d-preview.png')})
  await s.getByRole('button',{name:'巡航',exact:true}).click()
  await s.getByRole('button',{name:'山地实景',exact:true}).click()
  await page.waitForTimeout(3000)
  await page.waitForFunction(()=>!document.querySelector('.screen-map-loading'),{},{timeout:90000})
  console.log('ONLINE_TILES',{imageryTiles,terrainTiles})
  if(!imageryTiles||!terrainTiles)throw new Error('Real imagery or elevation tiles were not received')
  await page.screenshot({path:path.resolve('screen3d-terrain-preview.png')})
  await s.getByRole('button',{name:'倾斜视角',exact:true}).click()
  await s.getByRole('button',{name:'俯视',exact:true}).click()
  await s.getByRole('button',{name:'关闭巡航设置'}).click()
  await s.getByRole('button',{name:'图层',exact:true}).last().click()
  await s.getByText('气象格点场',{exact:true}).click()
  await s.getByRole('button',{name:'预报',exact:true}).click()
  await s.getByRole('button',{name:'下一帧',exact:true}).click()
  await page.waitForFunction(()=>!document.querySelector('.screen-loading'),{},{timeout:120000})
  await s.locator('.screen-left select').nth(1).selectOption('t2m')
  await page.waitForFunction(()=>!document.querySelector('.screen-loading'),{},{timeout:120000})
  await s.getByRole('button',{name:'区域定位',exact:true}).click()
  await s.getByRole('button',{name:'北京',exact:false}).first().click()
  await page.waitForFunction(()=>!!document.querySelector('.screen-chart canvas'),{},{timeout:120000})
  console.log('POINT',await s.locator('.screen-right').innerText())
  await s.getByRole('button',{name:'预报',exact:true}).click()
  await s.locator('.screen-left select').first().selectOption('probability')
  await page.waitForFunction(()=>!document.querySelector('.screen-loading'),{},{timeout:120000})
  if(await page.locator('.screen-alert').count())throw new Error(await page.locator('.screen-alert').innerText())
  await s.getByRole('button',{name:'巡航',exact:true}).click()
  await s.getByRole('button',{name:'开始巡航',exact:true}).click()
  await s.getByRole('button',{name:'暂停巡航',exact:true}).click()
  await s.getByRole('button',{name:'播放',exact:true}).click()
  await s.getByRole('button',{name:'暂停',exact:true}).click()
  await page.locator('.independent-header').getByRole('button',{name:'全屏',exact:true}).click()
  await page.locator('.independent-header').getByRole('button',{name:'退出全屏',exact:true}).click()
  await page.getByRole('button',{name:'返回工作台',exact:false}).click()
  await page.getByRole('button',{name:'3D大屏',exact:true}).click()
  await page.waitForFunction(()=>!!document.querySelector('.screen-globe canvas')&&!document.querySelector('.screen-loading'),{},{timeout:180000})
  await page.route('**/tiles.maps.eox.at/**',route=>route.abort())
  await page.route('**/elevation3d.arcgis.com/**',route=>route.abort())
  await page.reload()
  await page.getByRole('button',{name:'3D大屏',exact:true}).click()
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('.screen-note')).some(e=>e.textContent.includes('影像不可用'))&&Array.from(document.querySelectorAll('.screen-note')).some(e=>e.textContent.includes('地形不可用')),{},{timeout:45000})
  await page.waitForFunction(()=>!document.querySelector('.screen-loading'),{},{timeout:120000})
  if(await page.locator('.screen-alert').count())throw new Error('Fallback blocked the forecast scene')
  console.log('PASS: blocked imagery/elevation connections fall back without blocking forecast data')
  console.log('PAGE_ERRORS',JSON.stringify(errors))
  if(errors.length)throw new Error(errors.join('\n'))
  console.log('PASS: real satellite/elevation tiles, mountain/oblique views, next frame, temperature, province point, ensemble, tour, playback, fullscreen and remount')
  await browser.close()
}
main().catch(e=>{console.error(e);process.exit(1)})
